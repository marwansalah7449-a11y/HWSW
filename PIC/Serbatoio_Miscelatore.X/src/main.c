#include "eh100.h"

////////////////////////////////////////////////////////////////////////////////
// system includes
////////////////////////////////////////////////////////////////////////////////
#include <stdbool.h>
#include <stdint.h>
#include <xc.h>


////////////////////////////////////////////////////////////////////////////////
// constants
////////////////////////////////////////////////////////////////////////////////
#define DEBOUNCE_CYCLES 20

//define IO pins
#define M output_port.DOUT0
#define E1 output_port.DOUT1
#define E2 output_port.DOUT2
#define E3 output_port.DOUT3
#define CYCLE output_port.DOUT4

#define START (input_port.DIN7)
#define S1 !(input_port.DIN1)
#define S2 !(input_port.DIN2)
#define S3 !(input_port.DIN3)

////////////////////////////////////////////////////////////////////////////////
// private functions
////////////////////////////////////////////////////////////////////////////////

void main(void) {
    eh100_init();
    uint8_t last_start = 0;
    
    while (1) {
        
        if(START){
            CYCLE = 1;
            E3 = 0;   
            E1 = 1;   
            E2 = 0;
            M  = 0;
            while (S2 == 0);
            
            E1 = 0;
            E2 = 1;
            M  = 1;  
            while (S3 == 0);
            
            E2 = 0;
            E3 = 1;
            
            while (S1 == 1) {      
                M = (S2 == 1);
            }
            
            E1 = 0;
            E2 = 0;
            E3 = 1;

        }else{
            CYCLE = 0;
            E1 = 0;
            E2 = 0;
            E3 = 1;
            M = 0;
        }
        
    }
}
